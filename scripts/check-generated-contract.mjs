// Verify src/api/generated-contract.ts exists, is non-empty, and its header
// points at the generator. The authoritative freshness check runs in the VPN
// repository (`python3 scripts/generate_openapi_schemas.py --check-client`);
// this guard catches accidental hand-edits and missing files locally.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const contractPath = path.join(root, 'src', 'api', 'generated-contract.ts');

if (!fs.existsSync(contractPath)) {
  console.error(`✗ generated API contract is missing: ${contractPath}`);
  process.exit(1);
}

const text = fs.readFileSync(contractPath, 'utf8');
if (!text.includes('GENERATED by VPN-repo scripts/generate_openapi_schemas.py --client')) {
  console.error('✗ generated API contract header missing — the file was hand-edited or truncated.');
  process.exit(1);
}

const assertions = (text.match(/VexApiSpecExpect</g) || []).length;
if (assertions < 10) {
  console.error(`✗ generated API contract has too few assertions (${assertions}) — regenerate it.`);
  process.exit(1);
}

console.log(`✓ generated API contract present (${assertions} assertions)`);
